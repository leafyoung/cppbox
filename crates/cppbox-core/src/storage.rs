//! Disk-backed project storage. Each project = a folder under <root>/projects/<id>,
//! unless `local_path` is set (then that folder is the root). Mirrors backend/storage.py.
use std::path::{Path, PathBuf};

use serde_json::{json, Value};
/// Resolve a project's root folder.
pub fn project_root(root: &Path, id: &str, local_path: Option<&str>) -> PathBuf {
    match local_path {
        Some(p) if !p.is_empty() => PathBuf::from(p),
        _ => root.join("projects").join(id),
    }
}

/// Join a relative path under a project root, rejecting traversal outside it.
pub fn safe_join(root: &Path, id: &str, local_path: Option<&str>, rel: &str) -> Result<PathBuf, String> {
    use path_clean::PathClean;
    let base = project_root(root, id, local_path);
    // lexical normalization resolves `..` so `../escape` is caught even when the
    // target file does not yet exist (canonicalize() would fail on a new file).
    let target = base.join(rel).clean();
    let base = base.clean();
    if !target.starts_with(&base) {
        return Err("path escapes project root".into());
    }
    Ok(target)
}

pub fn write_file(root: &Path, id: &str, local_path: Option<&str>, rel: &str, content: &str) -> Result<String, String> {
    let target = safe_join(root, id, local_path, rel)?;
    if let Some(parent) = target.parent() {
        std::fs::create_dir_all(parent).map_err(|e| e.to_string())?;
    }
    std::fs::write(&target, content).map_err(|e| e.to_string())?;
    Ok(rel.to_string())
}

pub fn make_dir(root: &Path, id: &str, local_path: Option<&str>, rel: &str) -> Result<String, String> {
    let target = safe_join(root, id, local_path, rel)?;
    std::fs::create_dir_all(&target).map_err(|e| e.to_string())?;
    Ok(rel.to_string())
}

pub fn read_file(root: &Path, id: &str, local_path: Option<&str>, rel: &str) -> Result<String, String> {
    let target = safe_join(root, id, local_path, rel)?;
    std::fs::read_to_string(&target).map_err(|e| e.to_string())
}

pub fn delete_path(root: &Path, id: &str, local_path: Option<&str>, rel: &str) -> Result<(), String> {
    let target = safe_join(root, id, local_path, rel)?;
    if target.is_dir() {
        std::fs::remove_dir_all(&target).map_err(|e| e.to_string())
    } else {
        std::fs::remove_file(&target).map_err(|e| e.to_string())
    }
}

pub fn move_path(root: &Path, id: &str, local_path: Option<&str>, old: &str, new: &str) -> Result<String, String> {
    let from = safe_join(root, id, local_path, old)?;
    let to = safe_join(root, id, local_path, new)?;
    if let Some(parent) = to.parent() {
        std::fs::create_dir_all(parent).map_err(|e| e.to_string())?;
    }
    std::fs::rename(&from, &to).map_err(|e| e.to_string())?;
    Ok(new.to_string())
}

/// The per-project `.clangd` config text (CompileFlags + clang-tidy checks).
pub fn clangd_config_text(std: &str) -> String {
    format!(
        "CompileFlags:\n  Add: [-std={std}, -Wall, -Wextra]\nDiagnostics:\n  ClangTidy:\n    Add: [bugprone-*, performance-*, readability-*, modernize-*]\n    Remove: [readability-magic-numbers, readability-identifier-length, modernize-use-trailing-return-type, readability-function-cognitive-complexity, bugprone-easily-swappable-parameters]\n"
    )
}

/// Write the per-project .clangd (for host clangd / VS Code).
pub fn write_clangd_config(root: &Path, id: &str, local_path: Option<&str>, std: &str) {
    let d = project_root(root, id, local_path);
    let _ = std::fs::create_dir_all(&d);
    let _ = std::fs::write(d.join(".clangd"), clangd_config_text(std));
}

/// Per-project Makefile so `make` builds under VS Code Remote-SSH.
pub fn write_makefile(root: &Path, id: &str, local_path: Option<&str>, std: &str) {
    let d = project_root(root, id, local_path);
    let _ = std::fs::create_dir_all(&d);
    let body = "# Auto-generated by CPPBox\n\
CXX := clang++\n\
STD := {std}\n\
CXXFLAGS := -std=$(STD) -O2 -Wall -Wextra -pedantic\n\
SRCS := $(shell find . -type f \\( -name '*.cpp' -o -name '*.cc' -o -name '*.cxx' \\))\n\
HDRS := $(shell find . -type f \\( -name '*.h' -o -name '*.hpp' -o -name '*.hh' \\))\n\
DIRS := $(sort $(dir $(SRCS) $(HDRS)) .)\n\
INCS := $(patsubst %,-I%,$(DIRS))\n\
BIN := app\n\n\
all: $(BIN)\n\
$(BIN): $(SRCS)\n\
\t$(CXX) $(CXXFLAGS) $(INCS) $(SRCS) -o $(BIN)\n\
run: all\n\
\t./$(BIN)\n\
clean:\n\
\trm -f $(BIN)\n\
.PHONY: all run clean\n".replace("{std}", std);
    let _ = std::fs::write(d.join("Makefile"), body);
}

