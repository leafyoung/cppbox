/// Initialize a git repo in the project folder and write .gitignore.
pub fn git_init_project(root: &Path, id: &str, local_path: Option<&str>) {
    let d = project_root(root, id, local_path);
    if !d.exists() {
        return;
    }
    let _ = std::fs::write(d.join(".gitignore"), GITIGNORE);
    let _ = std::process::Command::new("git").arg("init").current_dir(&d)
        .stdout(std::process::Stdio::null()).stderr(std::process::Stdio::null()).status();
}

/// Read every source/header file for compilation. Returns (relative_name, content).
pub fn collect_source_files(root: &Path, id: &str, local_path: Option<&str>) -> Vec<(String, String)> {
    let base = project_root(root, id, local_path);
    let mut out = Vec::new();
    if !base.exists() {
        return out;
    }
    collect_into(&base, &base, &mut out);
    out.sort_by(|a, b| a.0.cmp(&b.0));
    out
}

const SRC_EXTS: [&str; 8] = ["cpp", "cc", "cxx", "c", "h", "hpp", "hh", "hxx"];

fn collect_into(base: &Path, dir: &Path, out: &mut Vec<(String, String)>) {
    let Ok(rd) = std::fs::read_dir(dir) else { return };
    for e in rd.flatten() {
        let name = e.file_name().to_string_lossy().into_owned();
        if name.starts_with('.') || name == "__pycache__" {
            continue;
        }
        let Ok(ft) = e.file_type() else { continue };
        if ft.is_dir() {
            collect_into(base, &e.path(), out);
        } else if ft.is_file() {
            let path = e.path();
            let ext = path.extension().and_then(|x| x.to_str()).unwrap_or("");
            if SRC_EXTS.contains(&ext) {
                if let Ok(rel) = path.strip_prefix(base) {
                    if let Ok(content) = std::fs::read_to_string(&path) {
                        out.push((rel.to_string_lossy().into_owned(), content));
                    }
                }
            }
        }
    }
}

/// Build the file-tree JSON the frontend expects:
/// `{name, type:"dir", path:"", children:[{name,type,path,children?}]}`
pub fn build_tree(root: &Path, id: &str, local_path: Option<&str>) -> Value {
    let base = project_root(root, id, local_path);
    let name = base
        .file_name()
        .map(|n| n.to_string_lossy().into_owned())
        .unwrap_or_default();
    if !base.exists() {
        return json!({ "name": name, "type": "dir", "path": "", "children": [] });
    }
    json!({ "name": name, "type": "dir", "path": "", "children": walk(&base, &base) })
}

fn walk(base: &Path, dir: &Path) -> Vec<Value> {
    let Ok(rd) = std::fs::read_dir(dir) else { return vec![] };
    let mut entries: Vec<_> = rd.flatten().collect();
    entries.sort_by(|a, b| {
        let ad = a.file_type().map(|t| t.is_dir()).unwrap_or(false);
        let bd = b.file_type().map(|t| t.is_dir()).unwrap_or(false);
        // directories first, then case-insensitive name
        bd.cmp(&ad).then_with(|| {
            a.file_name()
                .to_string_lossy()
                .to_lowercase()
                .cmp(&b.file_name().to_string_lossy().to_lowercase())
        })
    });
    let mut out = Vec::new();
    for e in entries {
        let fname = e.file_name().to_string_lossy().into_owned();
        if fname.starts_with('.') || fname == "__pycache__" {
            continue;
        }
        let Ok(ft) = e.file_type() else { continue };
        let rel = e
            .path()
            .strip_prefix(base)
            .map(|p| p.to_string_lossy().into_owned())
            .unwrap_or_default();
        if ft.is_dir() {
            out.push(json!({ "name": fname, "type": "dir", "path": rel, "children": walk(base, &e.path()) }));
        } else if ft.is_file() {
            out.push(json!({ "name": fname, "type": "file", "path": rel }));
        }
    }
    out
}

